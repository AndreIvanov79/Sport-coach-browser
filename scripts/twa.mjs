// Google Play: Trusted Web Activity projects for Bubblewrap, one per app, in android/<sport>/ (not committed: keystores live there).
// Usage: npm run twa                 writes android/<sport>/twa-manifest.json and BUILD.md from store/config.json
//        npm run twa -- --keys       also creates the upload keystores with keytool (asks for passwords)
//        npm run twa -- --version-code 7   forces the Android versionCode (each upload to Play needs a higher one)
import fs from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { SPORTS, APP, BACKGROUND, loadConfig, loadListings, configProblems, fingerprints, siteBase, FINGERPRINT } from "./store-lib.mjs";

const argv = process.argv, arg = name => { const i = argv.indexOf("--" + name); return i > 0 ? argv[i + 1] : undefined; };
const config = await loadConfig(), listings = await loadListings();
const problems = configProblems(config, { needAndroid: true });
if (problems.length) { console.error("Google Play apps need these fixes in store/config.json first:\n - " + problems.join("\n - ")); process.exit(1); }
const version = JSON.parse(await fs.readFile("package.json", "utf8")).version;
const [major, minor, patch] = version.split(".").map(Number), baseCode = major * 10000 + minor * 100 + patch;
const base = siteBase(config), host = new URL(base).host;

for (const sport of SPORTS) {
 const dir = "android/" + sport, file = dir + "/twa-manifest.json";
 await fs.mkdir(dir, { recursive: true });
 let previous = {}; try { previous = JSON.parse(await fs.readFile(file, "utf8")); } catch { /* first run */ }
 const prints = fingerprints(config, sport);
 for (const p of prints) if (!FINGERPRINT.test(p)) throw new Error(`playSigningSha256.${sport}: "${p}" is not a SHA-256 fingerprint`);
 const versionCode = Number(arg("version-code")) || Math.max(baseCode, previous.appVersionCode ?? 0);
 const manifest = {
  packageId: config.androidPackagePrefix + "." + sport,
  host,
  name: listings[sport].en.playTitle,
  launcherName: APP[sport].short,
  display: "standalone",
  orientation: "default",
  themeColor: BACKGROUND, themeColorDark: BACKGROUND,
  navigationColor: BACKGROUND, navigationColorDark: BACKGROUND,
  navigationDividerColor: BACKGROUND, navigationDividerColorDark: BACKGROUND,
  backgroundColor: BACKGROUND,
  enableNotifications: false,
  startUrl: "/" + sport + "/",
  fullScopeUrl: base + sport + "/",
  webManifestUrl: base + sport + "/manifest.webmanifest",
  iconUrl: base + sport + "/icons/icon-512.png",
  maskableIconUrl: base + sport + "/icons/maskable-512.png",
  splashScreenFadeOutDuration: 300,
  signingKey: { path: "./upload.keystore", alias: "upload" },
  appVersion: version,
  appVersionCode: versionCode,
  shortcuts: [],
  generatorApp: "bubblewrap-cli",
  fallbackType: "customtabs",
  features: {},
  alphaDependencies: { enabled: false },
  enableSiteSettingsShortcut: true,
  isChromeOSOnly: false,
  isMetaQuest: false,
  minSdkVersion: 24,
  fingerprints: prints.map((value, i) => ({ name: i ? "key " + (i + 1) : "play", value })),
  additionalTrustedOrigins: [],
  retainedBundles: []
 };
 await fs.writeFile(file, JSON.stringify(manifest, null, 2) + "\n");
 await fs.writeFile(dir + "/BUILD.md", buildNotes(sport, manifest));
 if (argv.includes("--keys")) {
  try { await fs.access(dir + "/upload.keystore"); console.log(sport + ": upload.keystore already exists, kept."); }
  catch {
   console.log(`\n${sport}: creating ${dir}/upload.keystore (choose a password and keep it; keytool asks for it).`);
   const r = spawnSync("keytool", ["-genkeypair", "-v", "-keystore", dir + "/upload.keystore", "-alias", "upload", "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000", "-dname", "CN=" + config.developerName.replace(/[,=+<>#;"\\]/g, " ")], { stdio: "inherit" });
   if (r.error || r.status) { console.error("keytool failed: install JDK 17 (sudo apt install openjdk-17-jdk) and run again."); process.exit(1); }
  }
 }
 console.log(`${sport}: ${file} (${manifest.packageId}, versionCode ${versionCode}${prints.length ? ", " + prints.length + " fingerprint(s)" : ""})`);
}
console.log("\nNext: see android/<sport>/BUILD.md. Keep android/*/upload.keystore and its password safe; the folder is not committed.");

function buildNotes(sport, m) {
 return `# ${APP[sport].short}: Android app for Google Play

Generated by \`npm run twa\` from \`store/config.json\`. Edit the config, not \`twa-manifest.json\`, then run \`npm run twa\` again.

- Package: \`${m.packageId}\`
- Opens: ${m.fullScopeUrl} (Trusted Web Activity: Chrome without the address bar)
- Version: ${m.appVersion} (versionCode ${m.appVersionCode}; every upload to Play needs a higher versionCode: \`npm run twa -- --version-code N\`)

## Once per computer

1. JDK 17: \`sudo apt install openjdk-17-jdk\` (Ubuntu). Bubblewrap needs exactly 17.
2. Bubblewrap: \`npm i -g @bubblewrap/cli\` (1.27 or newer: it targets Android 16 / API 36, required by Google Play since 31.08.2026).
3. \`bubblewrap doctor\`. On the first run Bubblewrap asks where the JDK is (\`/usr/lib/jvm/java-17-openjdk-amd64\`)
   and offers to download the Android command-line tools: answer yes.

## Build

The website must already be online: Bubblewrap downloads the icon from ${m.iconUrl}.

\`\`\`
npm run twa -- --keys        # once: creates android/${sport}/upload.keystore (keytool asks for a password)
cd android/${sport}
bubblewrap build             # first time: answer "Yes" to generate the Android project; then the keystore passwords
\`\`\`

Results in \`android/${sport}/\`:
- \`app-release-bundle.aab\` — upload this to Play Console (Testing → Closed testing → Create release).
- \`app-release-signed.apk\` — for a quick test on your phone (\`adb install app-release-signed.apk\`).

## Link the app to the website (remove the browser bar)

1. Play Console → Test and release → App integrity → App signing: copy the **SHA-256** of the *app signing key*
   (and of the *upload key*) into \`store/config.json → playSigningSha256.${sport}\`.
2. \`npm run site\` and publish the site again (push to GitHub). It now serves \`${base}.well-known/assetlinks.json\`.
3. \`npm run twa\` and \`bubblewrap build\` again only if you also want the fingerprints recorded in twa-manifest.json
   (not required: verification uses the file on the website).
4. Check: install the app from the Play test track; it must open without the address bar. If the bar is there,
   test the domain, package and fingerprint at https://developers.google.com/digital-asset-links/tools/generator

## Updates

The app shows the website, so a new version of the site reaches Android users without a new upload.
Build and upload a new \`.aab\` only when the name, icon, colours, package or Android requirements change.
Keep \`upload.keystore\` and its password: without them you have to ask Google to reset the upload key.
`;
}

// Checks the store texts against the store limits and writes copy-paste sheets: artifacts/store/<sport>.md.
// Usage: npm run store
import fs from "node:fs/promises";
import { SPORTS, LANGS, APP, LIMITS, loadConfig, loadListings, listingProblems, configProblems, siteBase } from "./store-lib.mjs";

const config = await loadConfig(), listings = await loadListings();
const problems = listingProblems(listings);
if (problems.length) { console.error("Listing texts need fixes:\n - " + problems.join("\n - ")); process.exit(1); }
const pending = configProblems(config);
const site = pending.some(p => p.startsWith("siteUrl")) ? "<SITE>/" : siteBase(config);
const LANG_NAME = { en: "English", ru: "Russian", ro: "Romanian" };
const FIELDS = [
 ["name", "Name (Chrome / Edge / Firefox)"], ["summary", "Short description (Chrome / Edge manifest)"], ["amoSummary", "Firefox summary"],
 ["playTitle", "Google Play: app name"], ["playShort", "Google Play: short description"], ["description", "Description (all stores)"]
];
await fs.mkdir("artifacts/store", { recursive: true });
for (const sport of SPORTS) {
 const l = listings[sport];
 const lines = [`# ${APP[sport].short}: store texts`, "", "Generated by `npm run store` from `store/listings/" + sport + ".json`. Edit the JSON, not this file.", "",
  `- Privacy policy: ${site}privacy/`, `- Website: ${site}`, `- Web app: ${site}${sport}/`, `- Contact: ${config.contactEmail}`,
  `- Categories: Chrome: ${l.categories.chrome}; Edge: ${l.categories.edge}; Firefox: ${l.categories.firefox}; Google Play: ${l.categories.play}`, ""];
 for (const lang of LANGS) {
  lines.push(`## ${LANG_NAME[lang]}`, "");
  for (const [field, label] of FIELDS) {
   const text = l[lang][field];
   lines.push(`### ${label} · ${[...text].length}/${LIMITS[field]}`, "", "```text", text, "```", "");
  }
 }
 await fs.writeFile("artifacts/store/" + sport + ".md", lines.join("\n"));
}
console.log("Store texts OK (" + SPORTS.length * LANGS.length + " listings within limits): artifacts/store/<sport>.md");
if (pending.length) console.log("Still to fill in store/config.json before publishing:\n - " + pending.join("\n - "));
